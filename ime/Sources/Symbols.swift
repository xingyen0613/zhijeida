import Foundation

/// 半形符號對應的全形／中文標點。
enum Symbols {
    static let fullWidth: [String: String] = [
        ",": "，", ".": "。", ";": "；", ":": "：",
        "?": "？", "!": "！", "\\": "、",
        "(": "（", ")": "）", "[": "「", "]": "」",
        "{": "『", "}": "』", "<": "《", ">": "》",
        "'": "‘", "\"": "“", "`": "・",
        "-": "－", "=": "＝", "+": "＋", "*": "＊", "/": "／",
        "@": "＠", "#": "＃", "$": "＄", "%": "％", "&": "＆",
        "^": "＾", "_": "＿", "|": "｜", "~": "～",
    ]

    static func full(_ halfWidth: String) -> String? {
        fullWidth[halfWidth]
    }
}
